@case
def main_moved_recut(path):
    """Green, but main moved since the cut: main stays where it is, and a new train is cut on the new main."""
    with Scenario(path) as sc:
        sc.riders()
        old_tip = sc.tip()
        sc.push_main({"other.txt": "other\n"}, "another lane's merge")
        new_main = sc.main_sha()
        sc.add_run(5, old_tip, conclusion="success")
        dispatched = len(sc.gh.dispatches)
        out = sc.step()
        expect(sc.main_sha() == new_main, "main was moved to the old tip")
        expect(sc.gh.bare_rev("refs/heads/train^1^1") == new_main, "the new train isn't cut on the new main")
        expect(sc.train_heads() == [1, 2], f"train merged {sc.train_heads()}")
        expect(sc.gh.dispatches[dispatched:] == [("train", "train")], f"dispatches {sc.gh.dispatches}")
        expect(sc.labels(1) == ["riding", "train"] and sc.labels(2) == ["riding", "train"], "labels changed")
        expect(not any("Landed" in c for n in (1, 2) for c in sc.comments(n)), "a PR was called landed")
        expect("main moved since the cut" in out, out)


@case
def slots_taken(path):
    """Three other PR runs going (the slots when CI_SLOTS isn't set): nothing is cut."""
    with Scenario(path) as sc:
        sc.open_pr(1, "first", {"a.txt": "one\n"})
        sc.add_run(20, "0" * 40, event="pull_request", branch="pr-x", status="in_progress", conclusion=None)
        sc.add_run(21, "0" * 40, event="pull_request", branch="pr-y", status="queued", conclusion=None)
        sc.add_run(22, "0" * 40, event="pull_request", branch="pr-z", status="queued", conclusion=None)
        before = sc.state()
        out = sc.step()
        expect(sc.state() == before and sc.tip() is None, "a train was cut while three runs went")
        expect("waiting: runs going" in out, out)


@case
def slots_from_variable(path):
    """Two other PR runs going: CI_SLOTS = 2 (the workflows' SLOTS) holds the train, the default of three cuts it."""
    with Scenario(path) as sc:
        sc.open_pr(1, "first", {"a.txt": "one\n"})
        sc.add_run(20, "0" * 40, event="pull_request", branch="pr-x", status="in_progress", conclusion=None)
        sc.add_run(21, "0" * 40, event="pull_request", branch="pr-y", status="queued", conclusion=None)
        os.environ["SLOTS"] = "2"
        try:
            out = sc.step()
        finally:
            del os.environ["SLOTS"]
        expect(sc.tip() is None and "waiting: runs going" in out, out)
        sc.step()
        expect(sc.tip() is not None, "no train cut with a slot free")


