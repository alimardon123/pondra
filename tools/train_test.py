@case
def nothing_to_land(path):
    """A PR main already has is dropped with "Nothing to land": its commit is in main, or the same change is."""
    with Scenario(os.path.join(path, "in-main")) as sc:
        sc.open_pr(1, "first", {"a.txt": "one\n"})
