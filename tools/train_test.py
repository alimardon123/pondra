import io
import os
import re
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import train  # noqa: E402
from train import GitHub, GitHubError  # noqa: E402

REPO = "owner/repo"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
WORKFLOW = ("This pull request's workflows aren't main's (it changes one, or main changed one since it "
            "branched), and the workflow's token may not push a workflow: merge main into it and label it train "
            "again, or label it ci if it changes a workflow.")
CASES = []


class Failed(Exception):
    pass


def expect(ok, why):
    if not ok:
        raise Failed(why)


def case(fn):
    """Registers a case; its docstring's first line is the name printed for it."""
    CASES.append(fn)
    return fn


def run_url(run_id):
    return f"https://github.test/{REPO}/actions/runs/{run_id}"


def sh(*args, cwd=None):
    """Runs a command that must succeed; its stdout, stripped."""
    return subprocess.run(args, check=True, capture_output=True, text=True, cwd=cwd).stdout.strip()


def git(repo, *args):
    return sh("git", "-C", repo, *args)


def identity(repo):
    git(repo, "config", "user.name", "train test")
    git(repo, "config", "user.email", "train-test@example.invalid")
    git(repo, "config", "commit.gpgsign", "false")


def write_commit(repo, edits, message):
    """Writes `edits` (path -> text) into a work tree and commits them."""
    for name, text in edits.items():
        path = os.path.join(repo, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", message)


class FakeGitHub(GitHub):
    """The GitHub calls, answered from dicts. main and the PR heads are refs of the bare origin: a PATCH of main
    is a fast-forward check, as GitHub's is, and a PR whose head is in the new main closes."""

    def __init__(self, bare):
        super().__init__(REPO)
        self.bare = bare
        self.prs = {}         # number -> {"title", "draft", "labels": [names], "files": [paths], "open"}
        self.comments = {}    # number -> [bodies]
        self.runs = []        # as the runs endpoint lists them, newest first
        self.jobs = {}        # run id -> [{"name", "conclusion"}]
        self.dispatches = []  # (ref, mode)
        self.reruns = []      # run ids
        self.writes = []      # (method, path) of every write made through api
        self.later = 0        # train.yml runs started (a wait's hand-over)

    def git(self, *args):
        return sh("git", "--git-dir", self.bare, *args)

    def bare_rev(self, ref):
        r = subprocess.run(["git", "--git-dir", self.bare, "rev-parse", "-q", "--verify", ref],
                           capture_output=True, text=True)
        return r.stdout.strip() or None

    def ancestor(self, a, b):
        return subprocess.run(["git", "--git-dir", self.bare, "merge-base", "--is-ancestor", a, b],
                              capture_output=True).returncode == 0

    def api(self, method, path, body=None):
        route = path.split("?")[0]
        if method != "GET":
            self.writes.append((method, route))
        base = f"repos/{REPO}"
        if method == "GET" and route == f"{base}/pulls":
            return [self.pr_json(n) for n in sorted(self.prs) if self.prs[n]["open"]]
        if method == "GET" and route == f"{base}/actions/workflows/build.yml/runs":
            return {"workflow_runs": self.runs}
        if method == "PATCH" and route == f"{base}/git/refs/heads/main":
            return self.move_main(body["sha"])
        if (m := re.fullmatch(rf"{base}/pulls/(\d+)/files", route)) and method == "GET":
            return [{"filename": f} for f in self.prs[int(m[1])]["files"]]
        if (m := re.fullmatch(rf"{base}/issues/(\d+)/labels", route)) and method == "POST":
            labels = self.prs[int(m[1])]["labels"]
            labels += [name for name in body["labels"] if name not in labels]
            return {}
        if (m := re.fullmatch(rf"{base}/issues/(\d+)/labels/(\S+)", route)) and method == "DELETE":
            return self.unlabel(int(m[1]), m[2])
        if (m := re.fullmatch(rf"{base}/issues/(\d+)/comments", route)) and method == "POST":
            self.comments.setdefault(int(m[1]), []).append(body["body"])
            return {}
        if (m := re.fullmatch(rf"{base}/actions/runs/(\d+)/jobs", route)) and method == "GET":
            return {"jobs": self.jobs.get(int(m[1]), [])}
        if (m := re.fullmatch(rf"{base}/actions/runs/(\d+)/rerun-failed-jobs", route)) and method == "POST":
            self.reruns.append(int(m[1]))
            return {}
        raise GitHubError(404, '{"message": "Not Found"}', f"gh: Not Found (HTTP 404) (fake: {method} {route})")

    def pr_json(self, n):
        pr = self.prs[n]
        return {"number": n, "title": pr["title"], "draft": pr["draft"],
                "labels": [{"name": name} for name in pr["labels"]],
                "head": {"repo": {"full_name": REPO}, "sha": self.bare_rev(f"refs/pull/{n}/head")}}

    def unlabel(self, n, name):
        labels = self.prs[n]["labels"]
        if name not in labels:
            raise GitHubError(404, '{"message": "Label does not exist"}', "gh: Label does not exist (HTTP 404)")
        labels.remove(name)
        return [{"name": left} for left in labels]

    def move_main(self, sha):
        if not self.ancestor(self.bare_rev("refs/heads/main"), sha):
            raise GitHubError(422, '{"message": "Update is not a fast forward"}',
                              "gh: Update is not a fast forward (HTTP 422)")
        self.git("update-ref", "refs/heads/main", sha)
        for n, pr in self.prs.items():
            if self.ancestor(self.bare_rev(f"refs/pull/{n}/head"), sha):
                pr["open"] = False
        return {}

    def dispatch(self, ref, mode):
        self.dispatches.append((ref, mode))

    def step_later(self):
        self.later += 1


class Scenario:
    """A bare origin with main, a clone of it (where `step` runs) and a FakeGitHub over the origin. `work` is a
    second clone that makes the commits: the PR heads and the pushes to main."""

    def __init__(self, path):
        self.bare = os.path.join(path, "origin.git")
        self.work = os.path.join(path, "work")
        self.clone = os.path.join(path, "clone")
        os.makedirs(path)
        sh("git", "init", "-q", "--bare", self.bare)
        sh("git", "--git-dir", self.bare, "symbolic-ref", "HEAD", "refs/heads/main")
        sh("git", "init", "-q", self.work)
        git(self.work, "symbolic-ref", "HEAD", "refs/heads/main")
        git(self.work, "remote", "add", "origin", self.bare)
        identity(self.work)
        write_commit(self.work, {"shared.txt": "base\n"}, "base")
        git(self.work, "push", "-q", self.bare, "HEAD:refs/heads/main")
        sh("git", "clone", "-q", self.bare, self.clone)
        identity(self.clone)
        self.gh = FakeGitHub(self.bare)

    def __enter__(self):
        self.cwd = os.getcwd()
        os.chdir(self.clone)
        return self

    def __exit__(self, *exc):
        os.chdir(self.cwd)
        return False

    def open_pr(self, n, title, edits, labels=("train",), draft=False):
        """Opens PR n: one commit of `edits` on main as it is now, its head at refs/pull/<n>/head in the origin."""
        git(self.work, "fetch", "-q", "origin")
        git(self.work, "checkout", "-q", "-B", f"pr{n}", "origin/main")
        write_commit(self.work, edits, title)
        git(self.work, "push", "-q", self.bare, f"HEAD:refs/pull/{n}/head")
        self.gh.prs[n] = {"title": title, "draft": draft, "labels": list(labels), "files": list(edits), "open": True}

    def push_main(self, edits, title):
        """A commit straight onto main, as another lane's merge would be."""
        git(self.work, "fetch", "-q", "origin")
        git(self.work, "checkout", "-q", "-B", "mainmove", "origin/main")
        write_commit(self.work, edits, title)
        git(self.work, "push", "-q", self.bare, "HEAD:refs/heads/main")

    def add_run(self, run_id, sha, *, event="workflow_dispatch", branch="train", status="completed",
                conclusion="failure", attempt=1, failed=("tests",)):
        """A build run as the runs endpoint lists it, with the jobs that failed in it."""
        self.gh.runs.insert(0, {"id": run_id, "event": event, "head_branch": branch, "head_sha": sha,
                                "status": status, "conclusion": conclusion, "run_attempt": attempt,
                                "html_url": run_url(run_id)})
        self.gh.jobs[run_id] = [{"name": name, "conclusion": "failure"} for name in failed]

    def step(self, dry=False):
        """One call of step. Returns the lines it printed."""
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            train.Train(self.gh, dry=dry).step()
        return out.getvalue()

    def conduct(self, minutes, dry=False):
        """One call of `step --wait minutes`. Returns the lines it printed."""
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            train.conduct(self.gh, dry=dry, minutes=minutes)
        return out.getvalue()

    def riders(self):
        """PRs 1 and 2 labelled train, and the step that cuts them into a train."""
        self.open_pr(1, "first", {"a.txt": "one\n"})
        self.open_pr(2, "second", {"b.txt": "two\n"})
        return self.step()

    def tip(self):
        return self.gh.bare_rev("refs/heads/train")

    def main_sha(self):
        return self.gh.bare_rev("refs/heads/main")

    def labels(self, n):
        return sorted(self.gh.prs[n]["labels"])

    def comments(self, n):
        return self.gh.comments.get(n, [])

    def train_heads(self):
        """The PR numbers the train merged, oldest first."""
        if self.tip() is None:
            return []
        log = self.gh.git("log", "--first-parent", "--reverse", "--format=%B", "refs/heads/main..refs/heads/train")
        return [int(n) for n in re.findall(r"^Train-Head: (\d+) ", log, re.M)]

    def state(self):
        """Everything a step can change, for the "nothing changed" checks."""
        return {"tip": self.tip(), "main": self.main_sha(), "dispatches": list(self.gh.dispatches),
                "open": sorted(n for n, pr in self.gh.prs.items() if pr["open"]),
                "labels": {n: self.labels(n) for n in self.gh.prs},
                "comments": {n: list(c) for n, c in self.gh.comments.items()}}


@case
def two_queued(path):
    """Two PRs labelled train: one step cuts train as main plus both, in order; both ride; one dispatch."""
    with Scenario(path) as sc:
        summary = os.path.join(path, "summary.md")
        os.environ["GITHUB_STEP_SUMMARY"] = summary
        try:
            out = sc.riders()
        finally:
            os.environ.pop("GITHUB_STEP_SUMMARY", None)
        expect(sc.train_heads() == [1, 2], f"train merged {sc.train_heads()}")
        expect(sc.gh.bare_rev("refs/heads/train^1^1") == sc.main_sha(), "train isn't main plus its merges")
        expect(sc.labels(1) == ["riding", "train"] and sc.labels(2) == ["riding", "train"],
               f"labels {sc.labels(1)} {sc.labels(2)}")
        expect(sc.gh.dispatches == [("train", "train")], f"dispatches {sc.gh.dispatches}")
        expect(f"cut #1 #2 onto {sc.main_sha()[:7]}" in out, out)
        with open(summary) as f:
            expect("cut #1 #2" in f.read(), "the step summary lacks the cut line")


@case
def run_going(path):
    """The train's run is going: nothing changes."""
    with Scenario(path) as sc:
        sc.riders()
        sc.add_run(5, sc.tip(), status="in_progress", conclusion=None)
        before, writes = sc.state(), len(sc.gh.writes)
        out = sc.step()
        expect(sc.state() == before and len(sc.gh.writes) == writes, "a step changed state while the run went")
        expect("waiting: run going" in out, out)


@case
def run_green_lands(path):
    """Green run: main moves to the train's tip, both PRs are commented as landed and lose their labels."""
    with Scenario(path) as sc:
        sc.riders()
        tip = sc.tip()
        sc.add_run(5, tip, conclusion="success")
        out = sc.step()
        expect(sc.main_sha() == tip, "main isn't the train's tip")
        for n in (1, 2):
            expect(sc.comments(n)[-1] == f"Landed with the train's run {run_url(5)}." + FOOTER,
                   f"comment on #{n}: {sc.comments(n)}")
            expect(sc.labels(n) == [], f"labels of #{n}: {sc.labels(n)}")
        expect(sc.gh.dispatches.count(("main", "main")) == 1 and sc.gh.dispatches[-1] == ("main", "main"),
               f"dispatches {sc.gh.dispatches}")
        expect("landed #1 #2" in out, out)


