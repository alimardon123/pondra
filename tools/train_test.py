@case
def lost_dispatch(path):
    """No run listed: a new tip is left alone; one more than ten minutes old is dispatched again, once."""
    with Scenario(path) as sc:
        sc.riders()
        dispatched = len(sc.gh.dispatches)
        out = sc.step()
        expect(len(sc.gh.dispatches) == dispatched and "waiting: run not listed yet" in out, out)
        real_now = train.now
        train.now = lambda: real_now() + 3600
        try:
            sc.step()
        finally:
            train.now = real_now
        expect(sc.gh.dispatches[dispatched:] == [("train", "train")], f"dispatches {sc.gh.dispatches}")


