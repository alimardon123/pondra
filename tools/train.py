#!/usr/bin/env python3
"""The merge train's conductor: many PRs land on main with one CI run.

A lane labels its PR `train` once its own checks passed. The conductor merges the queued PRs, in
order, onto main in a branch named `train`, starts CI on that branch once, and when that run is green
moves main to the train's tip (a fast-forward). So main becomes exactly the tree CI tested, and GitHub
marks each PR merged by itself. A check that can't flake (the build, the unit tests and static checks, the
forms check: anything outside FLAKY) fails the train the minute it fails: the run is stopped and judged then,
with no rerun. A red run whose failures can flake (the suites that run nodes) is retried once. Then the train
is halved (its first half is tested alone), so one PR can't hold the others for long. A PR labelled in the
first minutes of a train's run (JOIN) joins it: the train is cut again with it. One labelled later rides a car
stacked on the train: its merges go on the train's tip and get a run of their own, so it lands one run after the
train instead of two. Each car is the train up to a merge with a run of its own; the train lands at its furthest
green car, which tested every merge before it too. Only the front car's failures are judged (a car behind tests
the front's merges as well), and a new train stops the runs of the old one. Two cars run at most. A push to main
of its own (a PR that changes a workflow) means the train can't land: it is cut again on main at once. A PR that
changes a workflow can't ride (the workflow's token may not push one), but one that branched before main changed a
workflow does: its merge's first parent is main, with main's workflows. Should GitHub refuse that push, the train is
made again without the PRs whose workflows aren't main's, and they are told to merge main. `riding` marks the PRs
in the train now; only this script adds or removes it.

  python3 tools/train.py step [--dry-run] [--wait MINUTES]

Each step looks at GitHub and does the one next thing, so running it twice in a row is safe. With --wait,
while the train waits on its own run (not listed yet, going, its failed jobs rerun) it steps again each
minute, so a green run lands within a minute of its end; when the minutes run out it starts train.yml once
more to go on waiting. The workflow (.github/workflows/train.yml) runs it on a lane's label, at the end of
every build run and every 15 minutes, but the train's own run ends without starting it (GitHub starts no
workflow_run for a run the workflow's token began) and the schedule can lag by hours: the wait is what moves
the train. --dry-run prints each write it would make (labels, comments, the PATCH, pushes, dispatches,
reruns) and makes none, and steps once. tools/train_test.py runs these rules against a fake GitHub.
"""
import argparse
import json
import math
import os
import re
import subprocess
import sys
import time
from dataclasses import dataclass

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
CHANGES_WORKFLOW_NOTE = ("This pull request changes a workflow, which the workflow's token may not push: label it ci "
                         "to land it on its own.")
WORKFLOW_NOTE = ("This pull request's workflows aren't main's (main changed one since it branched), and GitHub "
                 "refused the train's push of its merge: merge main into it and label it train again.")
REFUSED = "refusing to allow"   # (GitHub's words when a push or a ref's move would change a workflow)
RED = ("failure", "timed_out", "startup_failure")  # job conclusions that count against the train
POLL = 60  # seconds between the steps of a wait
# The jobs whose failure can be a flake, so a red one is run again once before anyone is blamed: the suites that run
# nodes against the clock. From 10-24 12:00 to 10-25 18:00 reruns turned 4 of 8 red trains green, all in these
# (resilience 3 times, upgrade once, a harness part that hung). Any other job that fails a step fails the same way
# again: two red trains that day waited out a whole run and a rerun on a static check that failed in its first minute.
FLAKY = ("suite", "resilience", "upgrade", "sso", "sharing")
JOIN = 5 * 60  # seconds into a train's run in which a newly labelled PR joins it; later, it rides a car stacked on it
CARS = 2  # cars that run at once: each car's run takes a slot


class GitHubError(Exception):
    """A gh call that failed. `status` is GitHub's HTTP status (None when gh gave none), `stdout` what gh
    printed (GitHub's JSON answer, whose "message" says why) and `stderr` what gh said, which names the status."""

    def __init__(self, status, stdout, stderr):
        self.status, self.stdout, self.stderr = status, stdout, stderr
        super().__init__(stderr.strip() or f"HTTP {status}")


class GitHub:
    """The GitHub calls the train makes, through the gh command (which holds the token)."""

    def __init__(self, repo):
        self.repo = repo

    def _gh(self, args, data=None):
        r = subprocess.run(["gh", *args], input=data or "", capture_output=True, text=True)
        if r.returncode:
            status = re.search(r"HTTP (\d{3})", r.stderr)
            raise GitHubError(int(status[1]) if status else None, r.stdout, r.stderr)
        return r.stdout

    def api(self, method, path, body=None):
        """`gh api`: the parsed JSON answer, {} for an empty one. A body goes on standard input."""
        args = ["api", "--method", method, path]
        if body is not None:
            args += ["--input", "-"]
        out = self._gh(args, None if body is None else json.dumps(body))
        return json.loads(out) if out.strip() else {}

    def log(self, job_id):
        """A job's log, as text."""
        return self._gh(["api", f"repos/{self.repo}/actions/jobs/{job_id}/logs"])

    def dispatch(self, ref, mode):
        self._gh(["workflow", "run", "build.yml", "--repo", self.repo, "--ref", ref, "-f", f"mode={mode}"])

    def step_later(self):
        """Starts train.yml on main: the next step, once this one's run ends (they take turns)."""
        self._gh(["workflow", "run", "train.yml", "--repo", self.repo, "--ref", "main"])


@dataclass
class PR:
    number: int
    title: str
    labels: set
    head: str   # the PR's head commit as GitHub lists it now


def final(job):
    """A failed job's failure can't flake: a step failed, in a job outside FLAKY."""
    return not job["name"].startswith(FLAKY) and any(s.get("conclusion") in RED for s in job.get("steps") or [])


def pointed(log):
    """The files a job's log blames: where a compile error or a lint that failed points (`--> src/x.rs:3:5`, not a
    warning's), where a failed unit test panicked (`panicked at src/x.rs:3:5`), and the files that hold that test's
    module (`x::y::tests::name`: src/x/y.rs, src/x/y/mod.rs, src/x.rs)."""
    files, block, test = set(), None, None
    for line in re.sub(r"\x1b\[[0-9;]*m", "", log).splitlines():
        line = re.sub(r"^\d{4}-\d\d-\d\dT[\d:.]+Z ", "", line)   # (GitHub's timestamp on each line)
        if m := re.match(r"(error|warning)\b", line):
            block = m[1]
        elif not line.strip():
            block = None
        if m := re.fullmatch(r"---- ([\w:]+) stdout ----", line):
            test = m[1]
            parts = test.split("::tests::")[0].split("::") if "::tests::" in test else test.split("::")[:-1]
            for i in range(len(parts), 0, -1):
                files |= {f"src/{'/'.join(parts[:i])}.rs", f"src/{'/'.join(parts[:i])}/mod.rs"}
        elif line == "failures:":
            test = None
        where = re.search(r"(-->|panicked at) ((?:src|tools|tests|web)/[\w./-]+\.rs):\d", line)
        if where and (block == "error" if where[1] == "-->" else test is not None):
            files.add(where[2])
    return files


def git(*args):
    """git in the current directory (a full clone of main); a failure raises."""
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout.strip()


def git_ok(*args):
    """Whether git exits 0: for the questions git answers by exit code (ancestry, an empty diff)."""
    return subprocess.run(["git", *args], capture_output=True).returncode == 0


def conductor(rev):
    """The blob of this script at `rev`, or None where it has none."""
    r = subprocess.run(["git", "rev-parse", "-q", "--verify", f"{rev}:tools/train.py"], capture_output=True, text=True)
    return r.stdout.strip() or None


def now():
    """The clock, in its own function so a test can make a train's tip look old."""
    return time.time()


def pause(seconds):
    """A wait's sleep, in its own function so a test can make time pass."""
    time.sleep(seconds)


def say(line):
    """One line of what was done: stdout, and GitHub's step summary when the workflow has one."""
    print(line, flush=True)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as f:
            f.write(line + "\n\n")


class Train:
    """One call of `step`. With `dry` every write is printed instead of made; the reads still happen. `waiting`
    says, after it, whether the train waits on its own run (one going, rerun or just dispatched)."""

    def __init__(self, gh, dry=False):
        self.gh, self.dry, self.repo = gh, dry, gh.repo
        self.waiting = False
        # A PR whose workflows are main's as it branched rides though main changed one since: its merge's first
        # parent has main's. Strict, once GitHub refused such a push, it is dropped instead.
        self.strict = False

    def open_prs(self):
        """Open PRs against main that may ride: no forks, no drafts."""
        rows = self.gh.api("GET", f"repos/{self.repo}/pulls?state=open&base=main&per_page=100")
        return [PR(r["number"], r["title"], {label["name"] for label in r["labels"]}, r["head"]["sha"]) for r in rows
                if not r["draft"] and (r["head"].get("repo") or {}).get("full_name") == self.repo]

    def queue(self, prs=None):
        """Open PRs labelled train, oldest first, at most six: the riders of the next train."""
        prs = self.open_prs() if prs is None else prs
        return sorted((p for p in prs if "train" in p.labels), key=lambda p: p.number)[:6]

    def runs(self):
        return self.gh.api("GET", f"repos/{self.repo}/actions/workflows/build.yml/runs?per_page=100")["workflow_runs"]

    def train_runs(self):
        """The build runs dispatched on the train, newest first."""
        return [r for r in self.runs() if r["event"] == "workflow_dispatch" and r["head_branch"] == "train"]

    def slots(self, stopped=()):
        """Going runs that take a slot: a PR's run or a car's, but those just `stopped`. SLOTS may go at once
        (ci-slots.yml), no more."""
        return sum(1 for r in self.runs() if r["status"] != "completed" and r["id"] not in stopped and (
            r["event"] == "pull_request" or (r["event"] == "workflow_dispatch" and r["head_branch"] == "train")))

    def jobs(self, run_id):
        return self.gh.api("GET", f"repos/{self.repo}/actions/runs/{run_id}/jobs?per_page=100&filter=latest")["jobs"]

    def failed_jobs(self, run_id):
        """The run's failed jobs, so far, as {name: final}. A failure is final when a step failed in a job outside
        FLAKY: running it again changes nothing. A job that died with no failed step (its runner lost) may flake."""
        return {j["name"]: final(j) for j in self.jobs(run_id) if j["conclusion"] in RED}

    def blamed(self, prs, heads, run):
        """The riders whose changes a final failure's log points at (`pointed`), when that is some of them and not
        all: they are tested alone first, instead of the train's first half."""
        named = set()
        for j in self.jobs(run["id"]):
            if j["conclusion"] in RED and final(j):
                try:
                    named |= pointed(self.gh.log(j["id"]))
                except GitHubError as e:   # (a log GitHub no longer has, or won't give: no blame from it)
                    say(f"no log of {j['name']}: {e}")
        if not named:
            return []
        changed = {p.number: set(git("diff", "--name-only", f"origin/main...{heads[p.number]}").split()) for p in prs}
        suspects = [p for p in prs if changed[p.number] & named]
        return suspects if len(suspects) < len(prs) else []

    def bisecting(self, tip):
        """Whether the train's run before this one failed: then this train was cut from a red one (halved, or cut
        again on a moved main) to test its riders alone, and nobody joins it."""
        prev = next((r for r in self.runs() if r["event"] == "workflow_dispatch" and r["head_branch"] == "train"
                     and r["head_sha"] != tip), None)
        if prev is None or prev["conclusion"] == "success":
            return False
        return prev["conclusion"] in ("failure", "timed_out") or any(self.failed_jobs(prev["id"]).values())

    def main_failed(self):
        """The jobs that failed in main's latest run that ran. A red train that fails the same way isn't the train's."""
        run = next((r for r in self.runs() if r["head_branch"] == "main" and r["status"] == "completed"
                    and r["conclusion"] not in ("cancelled", "skipped")), None)
        return set(self.failed_jobs(run["id"])) if run else set()

    def fetch_train(self):
        """origin/train's tip after a fetch, or None when GitHub has no train branch (it may not exist yet)."""
        if not git("ls-remote", "origin", "refs/heads/train"):
            return None
        git("fetch", "origin", "train")
        return git("rev-parse", "origin/train")

    def train_merges(self, tip):
        """The train's merges as (PR number, PR head sha, merge sha), oldest first, and the main it was cut on. Both are
        written in the commits (Train-Head, Train-Base), so the train keeps no state of its own. ([], None) unless
        the tip is exactly what a cut makes, which is what lands on main: from the base, one merge a PR, each the
        clean merge of the commit before it and the head it names. A push to `train` from anywhere else (another
        commit, or a merge carrying more than its PR) never lands: the train is cut again."""
        base = re.search(r"^Train-Base: ([0-9a-f]{40})$", git("log", "-1", "--format=%B", tip), re.M)
        if not base:
            say(f"the train's tip isn't what a cut makes ({tip[:7]} names no base): cutting it again")
            return [], None
        merges, before = [], base[1]
        for row in git("log", "--first-parent", "--reverse", "--format=%H %T %P%x01%B%x00", f"{base[1]}..{tip}").split("\0"):
            if not row.strip():
                continue
            shas, body = row.strip().split("\x01", 1)
            sha, tree, *parents = shas.split()
            head = re.search(r"^Train-Head: (\d+) ([0-9a-f]{40})$", body, re.M)
            if not head or parents != [before, head[2]] or f"Train-Base: {base[1]}" not in body \
                    or subprocess.run(["git", "merge-tree", "--write-tree", before, head[2]],
                                      capture_output=True, text=True).stdout.split("\n")[0] != tree:
                say(f"the train's tip isn't what a cut makes ({sha[:7]}): cutting it again")
                return [], None
            merges.append((int(head[1]), head[2], sha))
            before = sha
        return merges, base[1]

    def tip_age(self, tip):
        return now() - int(git("log", "-1", "--format=%ct", tip))

    def write(self, method, path, body=None):
        """One write to GitHub. A dry run prints it instead."""
        if self.dry:
            print(f"dry run: {method} {path}" + ("" if body is None else f" {json.dumps(body)}"))
            return {}
        return self.gh.api(method, path, body)

    def push(self, fresh=True):
        """Pushes the train: as a new branch (`fresh`), since GitHub refuses the workflow's token a push that changes
        a workflow and moving the old train to a main whose workflows changed since would; or as a fast-forward, a
        car stacked on it. False when GitHub refused it for a workflow: then the train is made again `strict`."""
        if self.dry:
            print("dry run: git push origin train" + (" (the old one deleted first)" if fresh else ""))
            return True
        if fresh:
            git_ok("push", "origin", "--delete", "train")
        r = subprocess.run(["git", "push", "origin", "train"], capture_output=True, text=True)
        if r.returncode and REFUSED in r.stderr and not self.strict:
            say(f"GitHub refused the train's push for a workflow: {' '.join(r.stderr.split())[:300]}")
            self.strict = True
            return False
        if r.returncode:
            raise subprocess.CalledProcessError(r.returncode, r.args, r.stdout, r.stderr)
        return True

    def cancel(self, run):
        """Stops the train's run. A 409 means it ended in the meantime: the next step reads how."""
        try:
            self.write("POST", f"repos/{self.repo}/actions/runs/{run['id']}/cancel")
        except GitHubError as e:
            if e.status != 409:
                raise

    def dispatch(self, ref, mode):
        if self.dry:
            print(f"dry run: dispatch build.yml on {ref} (mode {mode})")
        else:
            self.gh.dispatch(ref, mode)

    def comment(self, n, text):
        self.write("POST", f"repos/{self.repo}/issues/{n}/comments", {"body": text + FOOTER})

    def unlabel(self, p, name):
        """Takes a label off a PR, if the listing showed it there. A 404 means it is already gone."""
        if name not in p.labels:
            return
        try:
            self.write("DELETE", f"repos/{self.repo}/issues/{p.number}/labels/{name}")
        except GitHubError as e:
            if e.status != 404:
                raise
        p.labels.discard(name)

    def step(self):
        """Does the one next thing (the rules are in the module docstring)."""
        prs = self.open_prs()
        riding = [p for p in prs if "riding" in p.labels]
        if riding:
            return self.follow(riding)
        return self.cut(self.queue(prs))

    def follow(self, riding):
        """Riders exist, so the cars' runs decide: the furthest green car lands; else the front car's run going waits
        (or is stopped, for a final failure; or a PR joins it, or rides a car stacked on it), and a red one is rerun
        once if it may have flaked, then judged against main's own run, then halved."""
        git("fetch", "origin", "main")
        tip = self.fetch_train()
        merges, first = self.train_merges(tip) if tip else ([], None)
        base, shas = first, [sha for _, _, sha in merges]
        main = git("rev-parse", "origin/main")
        if main in shas:   # a car landed: the rest rides on, from main
            merges, base = merges[shas.index(main) + 1:], main
        by_number = {p.number: p for p in riding}
        if base is None or not merges or {n for n, _, _ in merges} != set(by_number):
            return self.cut(self.queue())   # a broken state: start over
        prs = [by_number[n] for n, _, _ in merges]
        if main != base:
            # Main moved since the cut, by a push of its own: the train can't land on it (that's no fast-forward), and
            # it may carry the fix for a red one. So the same riders are cut again on it now, before anyone is blamed
            # (the same ones, so a halved train stays halved).
            say("main moved since the cut: cutting the train again")
            return self.cut(prs)
        heads = {n: head for n, head, _ in merges}
        runs = {}
        for r in self.train_runs():
            runs.setdefault(r["head_sha"], r)   # (the newest run on each commit)
        ends = [i for i, (_, _, sha) in enumerate(merges) if sha in runs]   # each car's last merge
        green = [i for i in ends if runs[merges[i][2]]["conclusion"] == "success"]
        if green:
            at = green[-1]
            for i in ends[:ends.index(at)]:   # (their merges land with it: its run tested them too)
                self.cancel(runs[merges[i][2]])
            return self.land(prs[:at + 1], heads, runs[merges[at][2]], merges[at][2], prs[at + 1:])
        self.waiting = True   # until the front car's run is judged below
        if not ends:
            return self.unlisted(tip)
        front = ends[0]
        run = runs[merges[front][2]]
        prs = prs[:front + 1]
        failed = self.failed_jobs(run["id"])
        final = [name for name, last in failed.items() if last]
        if run["status"] != "completed":
            if not final:
                return self.going(merges, runs, ends, by_number, first, tip)
            if set(final) & self.main_failed():
                return say(f"waiting: main fails the same way: {', '.join(final)}")
            # A check that can't flake failed: the rest of the run changes nothing, so it stops and is judged now.
            self.cancel(run)
            say(f"stopped the train's run: {', '.join(final)} failed")
        self.waiting = False
        if not failed:
            return self.cut(self.queue())   # cancelled, skipped, or red with no job to blame: cut and run it again
        if run["run_attempt"] == 1 and not final:
            # One rerun before blaming anyone: a flaky job isn't the train's fault.
            self.write("POST", f"repos/{self.repo}/actions/runs/{run['id']}/rerun-failed-jobs")
            self.waiting = True
            return say(f"rerun the train's failed jobs: {', '.join(failed)}")
        if set(failed) & self.main_failed():
            # Not a wait on the train's own run: main's next run, which a merge starts, steps again when it ends.
            return say(f"waiting: main fails the same way: {', '.join(failed)}")
        return self.halve(prs, run, failed, heads)

    def going(self, merges, runs, ends, by_number, first, tip):
        """The front car's run goes with nothing final failed. A car behind it with a final failure is stopped (it is
        judged once it is the front). A PR labelled since the cut joins a young train, or rides a car stacked on it."""
        for i in ends[1:]:
            r = runs[merges[i][2]]
            failed = self.failed_jobs(r["id"]) if r["status"] != "completed" else {}
            if any(failed.values()):
                self.cancel(r)
                say(f"stopped the run of the car ending at #{merges[i][0]}: "
                    f"{', '.join(n for n, last in failed.items() if last)} failed")
        if ends[-1] != len(merges) - 1:
            return self.unlisted(tip)   # the car stacked last isn't listed yet
        riders = [by_number[n] for n, _, _ in merges]
        joining = [p for p in self.open_prs() if "train" in p.labels and "riding" not in p.labels]
        joining = sorted(joining, key=lambda p: p.number)[:6]
        if joining and len(ends) == 1 and len(riders) < 6 and self.tip_age(tip) <= JOIN and not self.bisecting(tip):
            # Cut again with them after the riders: the riders lose the minutes run so far, the joiners a run's wait.
            say(f"{' '.join(f'#{p.number}' for p in joining[:6 - len(riders)])} joined the train: cutting it again")
            self.waiting = False
            return self.cut(riders + joining[:6 - len(riders)])
        if joining and len(ends) < CARS and self.slots() < int(os.environ.get("SLOTS") or 3):
            return self.stack(riders, joining, first, tip)
        return say("waiting: run going")

    def unlisted(self, tip):
        """The run of the train's tip isn't listed. A run takes up to a minute to be, and a dispatch can be lost: only
        an old tip is dispatched again."""
        if self.tip_age(tip) <= 600:
            return say("waiting: run not listed yet")
        say("dispatched the train again: its run was never listed")
        return self.dispatch("train", "train")

    def halve(self, prs, run, failed, heads):
        """A red train judged (on its second attempt, or at a final failure): a single PR is dropped with its failed
        jobs; of more, those whose changes the failure's log names (`blamed`) are cut and tested alone, or else the
        first half; the rest keep their train label and wait in the queue."""
        names = ", ".join(failed)
        if len(prs) > 1 and (blamed := self.blamed(prs, heads, run)):
            say(f"{names} failed where {' '.join(f'#{p.number}' for p in blamed)} changed: testing "
                f"{'it' if len(blamed) == 1 else 'them'} alone")
            return self.cut(blamed)
        if len(prs) == 1:
            p = prs[0]
            self.unlabel(p, "riding")
            self.unlabel(p, "train")
            self.comment(p.number, f"The train's run failed with this pull request alone on main: {names}. "
                                   f"{run['html_url']}. Fix it, then label it train again.")
            say(f"dropped #{p.number}: {names}")
            return self.cut(self.queue())
        half = math.ceil(len(prs) / 2)
        say(f"halved the train: {len(prs)} to {half}")
        return self.cut(prs[:half])

    def land(self, prs, heads, run, sha, rest):
        """Moves main to a green car's last merge, `sha`. GitHub refuses unless that is a fast-forward, which is the
        guard against a push to main since the cut: then main is cut again on its new head, and tested again. The PRs
        of the cars behind it (`rest`) ride on."""
        try:
            self.write("PATCH", f"repos/{self.repo}/git/refs/heads/main", {"sha": sha, "force": False})
        except GitHubError as e:
            if REFUSED in f"{e.stdout} {e.stderr}":
                say("GitHub refused main the train's merges for a workflow: cutting it again without them")
                self.strict = True
                return self.cut(self.queue())
            if e.status != 422:
                raise
            say("main moved since the cut: cutting the train again")
            return self.cut(self.queue())
        for p in prs:
            self.unlabel(p, "riding")
            self.unlabel(p, "train")
            landed = heads[p.number]
            if p.head == landed:
                self.comment(p.number, f"Landed with the train's run {run['html_url']}.")
            else:   # its lane pushed more while it rode: GitHub keeps it open with those commits alone
                self.comment(p.number, f"Landed {landed[:7]} with the train's run {run['html_url']}. What was pushed "
                                       "since is still open here: label it train again to land it.")
        say(f"landed {' '.join(f'#{p.number}' for p in prs)} on {sha[:7]}")
        # A push made with the workflow's token starts no run of its own, so main's run is dispatched here.
        self.dispatch("main", "main")
        if rest:
            self.waiting = True   # on the car behind
            return say(f"{' '.join(f'#{p.number}' for p in rest)} ride on")
        return self.cut(self.queue())

    def cut(self, prs):
        """Cuts the train on main's head from `prs`, in order, and starts its run. A PR that changes a workflow,
        conflicts or adds nothing loses its train label with a comment; the rest ride. The old train's runs still
        going stop: nothing lands from them now."""
        git("fetch", "origin", "main")
        stopped = [r["id"] for r in self.train_runs() if r["status"] != "completed"]
        for run_id in stopped:
            self.cancel({"id": run_id})
        if not prs:
            return self.set_riding([])   # nothing queued: no PR may keep riding a train that isn't there
        if self.slots(stopped) >= int(os.environ.get("SLOTS") or 3):
            return say("waiting: runs going")
        git("checkout", "-B", "train", "origin/main")
        base = git("rev-parse", "origin/main")
        merged = []
        for p in prs:
            self.merge(p, base, merged)
        if not merged:
            return self.set_riding(merged)
        if not self.push():
            return self.cut(prs)
        self.set_riding(merged)
        self.dispatch("train", "train")
        self.waiting = True
        say(f"cut {' '.join(f'#{n}' for n in merged)} onto {base[:7]}")

    def stack(self, riders, prs, base, tip):
        """Merges `prs` onto the train's tip as a car of their own, with its own run, while the front car's goes."""
        git("checkout", "-B", "train", tip)
        merged = [p.number for p in riders]
        for p in prs:
            self.merge(p, base, merged)
        if len(merged) == len(riders):
            self.set_riding(merged)
            return say("waiting: run going")
        if not self.push(fresh=False):   # (a fast-forward: the front car's run goes on, on its own commit)
            return self.stack(riders, prs, base, tip)
        self.set_riding(merged)
        self.dispatch("train", "train")
        say(f"stacked {' '.join(f'#{n}' for n in merged[len(riders):])} on the train's run")

    def merge(self, p, base, merged):
        """Merges a PR onto the train (its number goes to `merged`), or takes it out of the train: a conflict, or
        nothing that main doesn't already have."""
        git("fetch", "origin", f"pull/{p.number}/head")
        sha = git("rev-parse", "FETCH_HEAD")
        if not git_ok("diff", "--quiet", base, "FETCH_HEAD", "--", ".github/workflows/"):   # its workflows aren't main's
            fork = subprocess.run(["git", "merge-base", base, "FETCH_HEAD"], capture_output=True, text=True).stdout
            if not git_ok("diff", "--quiet", fork.strip() or base, "FETCH_HEAD", "--", ".github/workflows/"):
                # It changes a workflow (since it branched from main), which the workflow's token may not push.
                self.unlabel(p, "train")
                self.comment(p.number, CHANGES_WORKFLOW_NOTE)
                return say(f"dropped #{p.number}: it changes a workflow")
            if self.strict:
                self.unlabel(p, "train")
                self.comment(p.number, WORKFLOW_NOTE)
                return say(f"dropped #{p.number}: its workflows aren't main's")
        if git_ok("merge-base", "--is-ancestor", "FETCH_HEAD", "HEAD"):
            return self.nothing_to_land(p)   # the train already holds it: no merge to make
        r = subprocess.run(["git", "merge", "--no-ff", "--no-edit", "-m", f"{p.title} (#{p.number})",
                            "-m", f"Train-Head: {p.number} {sha}", "-m", f"Train-Base: {base}", "FETCH_HEAD"],
                           capture_output=True, text=True)
        if r.returncode:
            # (a merge git refused with no conflict, unrelated histories say, is the PR's too: it leaves the train
            # with what git said, and the train goes on without it)
            refused = None if git("diff", "--name-only", "--diff-filter=U") else (r.stderr.strip() or r.stdout.strip())
            git_ok("merge", "--abort")   # (there's none to abort when git refused to start it)
            git("reset", "--hard", "HEAD")
            git("clean", "-fd")
            return self.conflict(p, merged, refused)
        if git_ok("diff", "--quiet", "HEAD^1", "HEAD"):
            git("reset", "--hard", "HEAD^")   # the merge changed nothing: take it back
            return self.nothing_to_land(p)
        merged.append(p.number)

    def nothing_to_land(self, p):
        self.unlabel(p, "train")
        self.comment(p.number, "Nothing to land: main, or a pull request ahead of it in the train, already has its changes.")
        say(f"dropped #{p.number}: nothing to land")

    def conflict(self, p, merged, refused=None):
        after = f" after {', '.join(f'#{n}' for n in merged)} in the train" if merged else ""
        self.unlabel(p, "train")
        if refused:
            said = " ".join(refused.split())[:300]
            self.comment(p.number, f"This pull request doesn't merge onto main{after}: git refused the merge with no "
                                   f"conflict (`{said}`). Label it train again once that is fixed.")
            return say(f"dropped #{p.number}: git refused the merge: {said}")
        self.comment(p.number, f"This pull request doesn't merge onto main{after}: merge main into it, "
                               "then label it train again.")
        say(f"dropped #{p.number}: conflicts")

    def set_riding(self, merged):
        """`riding` goes on exactly the PRs merged into the train, and off every other open PR."""
        for p in self.open_prs():
            if p.number not in merged:
                self.unlabel(p, "riding")
            elif "riding" not in p.labels:
                self.write("POST", f"repos/{self.repo}/issues/{p.number}/labels", {"labels": ["riding"]})


def conduct(gh, dry=False, minutes=0):
    """Steps, and steps again each POLL seconds while the train waits on its own run, for up to `minutes`. When
    they run out with the train still waiting, train.yml is started once more to go on; and as soon as main has
    another copy of this script, so the new one conducts from its next minute. A dry run steps once."""
    end = now() + minutes * 60
    mine = conductor("origin/main")   # (train.yml checks out main: this copy)
    while True:
        train = Train(gh, dry)
        train.step()
        if dry or not train.waiting or not minutes:
            return
        if mine and conductor("origin/main") not in (None, mine):
            say("main has a new conductor: train.yml goes on waiting with it")
            return gh.step_later()
        if now() + POLL > end:
            say(f"waited {minutes} minutes: train.yml goes on waiting")
            return gh.step_later()
        pause(POLL)


def main(argv=None):
    ap = argparse.ArgumentParser(description="The merge train's conductor (see the module docstring).")
    ap.add_argument("command", choices=["step"])
    ap.add_argument("--dry-run", action="store_true", help="print each write instead of making it")
    ap.add_argument("--wait", type=int, default=0, metavar="MINUTES",
                    help="step again each minute while the train waits on its own run, for up to MINUTES")
    args = ap.parse_args(argv)
    repo = os.environ.get("GITHUB_REPOSITORY")
    if not repo:
        print("train: GITHUB_REPOSITORY is not set (owner/name of this repository)", file=sys.stderr)
        return 1
    try:
        conduct(GitHub(repo), dry=args.dry_run, minutes=args.wait)
    except (GitHubError, RuntimeError, subprocess.CalledProcessError) as e:
        print(f"train: {e}\n{getattr(e, 'stderr', '') or ''}".rstrip(), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
