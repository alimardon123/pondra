#!/usr/bin/env python3
"""The merge train's conductor: many PRs land on main with one CI run.

A lane labels its PR `train` once its own checks passed. The conductor merges the queued PRs, in
order, onto main in a branch named `train`, starts CI on that branch once, and when that run is green
moves main to the train's tip (a fast-forward). So main becomes exactly the tree CI tested, and GitHub
marks each PR merged by itself. A red run is retried once, then the train is halved (its first half is
tested alone), so one PR can't hold the others for long. `riding` marks the PRs in the train now; only
this script adds or removes it.

  python3 tools/train.py step [--dry-run]

Each call looks at GitHub, does the one next thing and exits, so running it twice in a row is safe.
The workflow (.github/workflows/train.yml) runs it on a lane's label, at the end of every build run and
every 15 minutes. --dry-run prints each write it would make (labels, comments, the PATCH, pushes,
dispatches, reruns) and makes none. tools/train_test.py runs these rules against a fake GitHub.
"""
import argparse
import json
import math
import os
import re
import subprocess
import sys
import time
from dataclasses import dataclass

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
WORKFLOW_NOTE = ("This pull request's workflows aren't main's (it changes one, or main changed one since it "
                 "branched), and the workflow's token may not push a workflow: merge main into it and label it train "
                 "again, or label it ci if it changes a workflow.")
RED = ("failure", "timed_out", "startup_failure")  # job conclusions that count against the train


class GitHubError(Exception):
    """A gh call that failed. `status` is GitHub's HTTP status (None when gh gave none), `stdout` what gh
    printed (GitHub's JSON answer, whose "message" says why) and `stderr` what gh said, which names the status."""

    def __init__(self, status, stdout, stderr):
        self.status, self.stdout, self.stderr = status, stdout, stderr
        super().__init__(stderr.strip() or f"HTTP {status}")


class GitHub:
    """The GitHub calls the train makes, through the gh command (which holds the token)."""

    def __init__(self, repo):
        self.repo = repo

    def _gh(self, args, data=None):
        r = subprocess.run(["gh", *args], input=data or "", capture_output=True, text=True)
        if r.returncode:
            status = re.search(r"HTTP (\d{3})", r.stderr)
            raise GitHubError(int(status[1]) if status else None, r.stdout, r.stderr)
        return r.stdout

    def api(self, method, path, body=None):
        """`gh api`: the parsed JSON answer, {} for an empty one. A body goes on standard input."""
        args = ["api", "--method", method, path]
        if body is not None:
            args += ["--input", "-"]
        out = self._gh(args, None if body is None else json.dumps(body))
        return json.loads(out) if out.strip() else {}

    def dispatch(self, ref, mode):
        self._gh(["workflow", "run", "build.yml", "--repo", self.repo, "--ref", ref, "-f", f"mode={mode}"])


@dataclass
class PR:
    number: int
    title: str
    labels: set
    head: str   # the PR's head commit as GitHub lists it now


def git(*args):
    """git in the current directory (a full clone of main); a failure raises."""
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout.strip()


def git_ok(*args):
    """Whether git exits 0: for the questions git answers by exit code (ancestry, an empty diff)."""
    return subprocess.run(["git", *args], capture_output=True).returncode == 0


def now():
    """The clock, in its own function so a test can make a train's tip look old."""
    return time.time()


def say(line):
    """One line of what was done: stdout, and GitHub's step summary when the workflow has one."""
    print(line, flush=True)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as f:
            f.write(line + "\n\n")


class Train:
    """One call of `step`. With `dry` every write is printed instead of made; the reads still happen."""

    def __init__(self, gh, dry=False):
        self.gh, self.dry, self.repo = gh, dry, gh.repo

    def open_prs(self):
        """Open PRs against main that may ride: no forks, no drafts."""
        rows = self.gh.api("GET", f"repos/{self.repo}/pulls?state=open&base=main&per_page=100")
        return [PR(r["number"], r["title"], {label["name"] for label in r["labels"]}, r["head"]["sha"]) for r in rows
                if not r["draft"] and (r["head"].get("repo") or {}).get("full_name") == self.repo]

    def queue(self, prs=None):
        """Open PRs labelled train, oldest first, at most six: the riders of the next train."""
        prs = self.open_prs() if prs is None else prs
        return sorted((p for p in prs if "train" in p.labels), key=lambda p: p.number)[:6]

    def runs(self):
        return self.gh.api("GET", f"repos/{self.repo}/actions/workflows/build.yml/runs?per_page=100")["workflow_runs"]

    def train_run(self, tip):
        """The newest build run dispatched on the train at its tip, or None."""
        return next((r for r in self.runs() if r["event"] == "workflow_dispatch" and r["head_branch"] == "train"
                     and r["head_sha"] == tip), None)

    def slots(self):
        """Going runs that take a slot: a PR's run or the train's. SLOTS may go at once (ci-slots.yml), no more."""
        return sum(1 for r in self.runs() if r["status"] != "completed" and (
            r["event"] == "pull_request" or (r["event"] == "workflow_dispatch" and r["head_branch"] == "train")))

    def failed_jobs(self, run_id):
        jobs = self.gh.api("GET", f"repos/{self.repo}/actions/runs/{run_id}/jobs?per_page=100&filter=latest")["jobs"]
        return [j["name"] for j in jobs if j["conclusion"] in RED]

    def main_failed(self):
        """The jobs that failed in main's latest run that ran. A red train that fails the same way isn't the train's."""
        run = next((r for r in self.runs() if r["head_branch"] == "main" and r["status"] == "completed"
                    and r["conclusion"] not in ("cancelled", "skipped")), None)
        return set(self.failed_jobs(run["id"])) if run else set()

    def fetch_train(self):
        """origin/train's tip after a fetch, or None when GitHub has no train branch (it may not exist yet)."""
        if not git("ls-remote", "origin", "refs/heads/train"):
            return None
        git("fetch", "origin", "train")
        return git("rev-parse", "origin/train")

    def train_merges(self, tip):
        """The train's merges as (PR number, PR head sha), oldest first, and the main it was cut on. Both are
        written in the commits (Train-Head, Train-Base), so the train keeps no state of its own."""
        base = re.search(r"^Train-Base: ([0-9a-f]{40})$", git("log", "-1", "--format=%B", tip), re.M)
        if not base:
            return [], None
        merges = []
        for body in git("log", "--first-parent", "--reverse", "--format=%B%x00", f"{base[1]}..{tip}").split("\0"):
            head = re.search(r"^Train-Head: (\d+) ([0-9a-f]{40})$", body, re.M)
            if head:
                merges.append((int(head[1]), head[2]))
        return merges, base[1]

    def tip_age(self, tip):
        return now() - int(git("log", "-1", "--format=%ct", tip))

    def write(self, method, path, body=None):
        """One write to GitHub. A dry run prints it instead."""
        if self.dry:
            print(f"dry run: {method} {path}" + ("" if body is None else f" {json.dumps(body)}"))
            return {}
        return self.gh.api(method, path, body)

    def push(self):
        """The train goes up as a new branch: GitHub refuses the workflow's token a push that changes a workflow,
        and moving the old train to a main whose workflows changed since would."""
        if self.dry:
            print("dry run: git push origin train (the old one deleted first)")
        else:
            git_ok("push", "origin", "--delete", "train")
            git("push", "origin", "train")

    def dispatch(self, ref, mode):
        if self.dry:
            print(f"dry run: dispatch build.yml on {ref} (mode {mode})")
        else:
            self.gh.dispatch(ref, mode)

    def comment(self, n, text):
        self.write("POST", f"repos/{self.repo}/issues/{n}/comments", {"body": text + FOOTER})

    def unlabel(self, p, name):
        """Takes a label off a PR, if the listing showed it there. A 404 means it is already gone."""
        if name not in p.labels:
            return
        try:
            self.write("DELETE", f"repos/{self.repo}/issues/{p.number}/labels/{name}")
        except GitHubError as e:
            if e.status != 404:
                raise
        p.labels.discard(name)

    def step(self):
        """Does the one next thing (the rules are in the module docstring)."""
        prs = self.open_prs()
        riding = [p for p in prs if "riding" in p.labels]
        if riding:
            return self.follow(riding)
        return self.cut(self.queue(prs))

    def follow(self, riding):
        """Riders exist, so the train's run decides: green lands it, a run going waits, and a red one is
        rerun once, then judged against main's own run, then halved."""
        git("fetch", "origin", "main")
        tip = self.fetch_train()
        merges, base = self.train_merges(tip) if tip else ([], None)
        by_number = {p.number: p for p in riding}
        if base is None or {n for n, _ in merges} != set(by_number):
            return self.cut(self.queue())   # a broken state: start over
        prs = [by_number[n] for n, _ in merges]
        heads = dict(merges)
        run = self.train_run(tip)
        if run is None:
            # A run takes up to a minute to be listed, and a dispatch can be lost: only an old tip is dispatched again.
            if self.tip_age(tip) <= 600:
                return say("waiting: run not listed yet")
            say("dispatched the train again: its run was never listed")
            return self.dispatch("train", "train")
        if run["status"] != "completed":
            return say("waiting: run going")
        if run["conclusion"] == "success":
            return self.land(prs, heads, run, tip)
        failed = self.failed_jobs(run["id"])
        if run["conclusion"] not in ("failure", "timed_out") or not failed:
            return self.cut(self.queue())   # cancelled, skipped, or red with no job to blame: cut and run it again
        if run["run_attempt"] == 1:
            # One rerun before blaming anyone: a flaky job isn't the train's fault.
            self.write("POST", f"repos/{self.repo}/actions/runs/{run['id']}/rerun-failed-jobs")
            return say(f"rerun the train's failed jobs: {', '.join(failed)}")
        if set(failed) & self.main_failed():
            return say(f"waiting: main fails the same way: {', '.join(failed)}")
        if git("rev-parse", "origin/main") != base:
            # Main moved since the cut, and may carry the fix: the same riders are cut again on it before anyone is
            # blamed (the same ones, so a halved train stays halved).
            say("main moved since the cut: cutting the red train again")
            return self.cut(prs)
        return self.halve(prs, run, failed)

    def halve(self, prs, run, failed):
        """A red train on its second attempt: a single PR is dropped with its failed jobs; more are halved, the
        first half cut and tested alone, and the rest keep their train label and wait in the queue."""
        names = ", ".join(failed)
        if len(prs) == 1:
            p = prs[0]
            self.unlabel(p, "riding")
            self.unlabel(p, "train")
            self.comment(p.number, f"The train's run failed with this pull request alone on main: {names}. "
                                   f"{run['html_url']}. Fix it, then label it train again.")
            say(f"dropped #{p.number}: {names}")
            return self.cut(self.queue())
        half = math.ceil(len(prs) / 2)
        say(f"halved the train: {len(prs)} to {half}")
        return self.cut(prs[:half])

    def land(self, prs, heads, run, tip):
        """Moves main to the train's tip. GitHub refuses unless that is a fast-forward, which is the guard against
        a push to main since the cut: then main is cut again on its new head, and tested again."""
        try:
            self.write("PATCH", f"repos/{self.repo}/git/refs/heads/main", {"sha": tip, "force": False})
        except GitHubError as e:
            if e.status != 422:
                raise
            say("main moved since the cut: cutting the train again")
            return self.cut(self.queue())
        for p in prs:
            self.unlabel(p, "riding")
            self.unlabel(p, "train")
            landed = heads[p.number]
            if p.head == landed:
                self.comment(p.number, f"Landed with the train's run {run['html_url']}.")
            else:   # its lane pushed more while it rode: GitHub keeps it open with those commits alone
                self.comment(p.number, f"Landed {landed[:7]} with the train's run {run['html_url']}. What was pushed "
                                       "since is still open here: label it train again to land it.")
        say(f"landed {' '.join(f'#{p.number}' for p in prs)} on {tip[:7]}")
        # A push made with the workflow's token starts no run of its own, so main's run is dispatched here.
        self.dispatch("main", "main")
        return self.cut(self.queue())

    def cut(self, prs):
        """Cuts the train on main's head from `prs`, in order, and starts its run. A PR that changes a workflow,
        conflicts or adds nothing loses its train label with a comment; the rest ride."""
        git("fetch", "origin", "main")
        if not prs:
            return self.set_riding([])   # nothing queued: no PR may keep riding a train that isn't there
        if self.slots() >= int(os.environ.get("SLOTS") or 3):
            return say("waiting: runs going")
        git("checkout", "-B", "train", "origin/main")
        base = git("rev-parse", "origin/main")
        merged = []
        for p in prs:
            self.merge(p, base, merged)
        self.set_riding(merged)
        if not merged:
            return
        self.push()
        self.dispatch("train", "train")
        say(f"cut {' '.join(f'#{n}' for n in merged)} onto {base[:7]}")

    def merge(self, p, base, merged):
        """Merges a PR onto the train (its number goes to `merged`), or takes it out of the train: a conflict, or
        nothing that main doesn't already have."""
        git("fetch", "origin", f"pull/{p.number}/head")
        sha = git("rev-parse", "FETCH_HEAD")
        if not git_ok("diff", "--quiet", "origin/main", "FETCH_HEAD", "--", ".github/workflows/"):
            # Its merge would differ from one of its parents in a workflow, which the workflow's token may not push.
            self.unlabel(p, "train")
            self.comment(p.number, WORKFLOW_NOTE)
            return say(f"dropped #{p.number}: its workflows aren't main's")
        if git_ok("merge-base", "--is-ancestor", "FETCH_HEAD", "HEAD"):
            return self.nothing_to_land(p)   # the train already holds it: no merge to make
        r = subprocess.run(["git", "merge", "--no-ff", "--no-edit", "-m", f"{p.title} (#{p.number})",
                            "-m", f"Train-Head: {p.number} {sha}", "-m", f"Train-Base: {base}", "FETCH_HEAD"],
                           capture_output=True, text=True)
        if r.returncode:
            if not git("diff", "--name-only", "--diff-filter=U"):
                raise RuntimeError(f"git merge of #{p.number} failed: {r.stderr.strip()}")
            git("merge", "--abort")
            git("reset", "--hard", "HEAD")
            git("clean", "-fd")
            return self.conflict(p, merged)
        if git_ok("diff", "--quiet", "HEAD^1", "HEAD"):
            git("reset", "--hard", "HEAD^")   # the merge changed nothing: take it back
            return self.nothing_to_land(p)
        merged.append(p.number)

    def nothing_to_land(self, p):
        self.unlabel(p, "train")
        self.comment(p.number, "Nothing to land: main, or a pull request ahead of it in the train, already has its changes.")
        say(f"dropped #{p.number}: nothing to land")

    def conflict(self, p, merged):
        after = f" after {', '.join(f'#{n}' for n in merged)} in the train" if merged else ""
        self.unlabel(p, "train")
        self.comment(p.number, f"This pull request doesn't merge onto main{after}: merge main into it, "
                               "then label it train again.")
        say(f"dropped #{p.number}: conflicts")

    def set_riding(self, merged):
        """`riding` goes on exactly the PRs merged into the train, and off every other open PR."""
        for p in self.open_prs():
            if p.number not in merged:
                self.unlabel(p, "riding")
            elif "riding" not in p.labels:
                self.write("POST", f"repos/{self.repo}/issues/{p.number}/labels", {"labels": ["riding"]})


def main(argv=None):
    ap = argparse.ArgumentParser(description="The merge train's conductor (see the module docstring).")
    ap.add_argument("command", choices=["step"])
    ap.add_argument("--dry-run", action="store_true", help="print each write instead of making it")
    args = ap.parse_args(argv)
    repo = os.environ.get("GITHUB_REPOSITORY")
    if not repo:
        print("train: GITHUB_REPOSITORY is not set (owner/name of this repository)", file=sys.stderr)
        return 1
    try:
        Train(GitHub(repo), dry=args.dry_run).step()
    except (GitHubError, RuntimeError, subprocess.CalledProcessError) as e:
        print(f"train: {e}\n{getattr(e, 'stderr', '') or ''}".rstrip(), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
